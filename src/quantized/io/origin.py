"""Origin export: a paired CSV + LabTalk ``.ogs`` script. Port of MATLAB
``+utilities/exportOriginScript.m``.

The ``.ogs`` script, when run in OriginPro, imports the accompanying CSV, sets
column designations, long names, units and comments, and optionally builds a
graph — a maintainable alternative to writing binary ``.opju`` files.

Designations come from the dataset's declared roles (``_column_roles``:
``column_designations`` + the live ``error_roles``), written as the LabTalk
``wks.col.type`` codes (1 Y, 2 Disregard, 3 yErr, 4 X, 5 Label, 6 Z, 7 xErr).
Only a dataset that declares NEITHER field falls back to the MATLAB label
guess, and that guess matches whole tokens (``"Kerr err"``, ``"dR"``), never
substrings (``"Kerr"``, ``"Hydrogen"``, ``"Standard"``, ``"Drift"`` are data).
The default graph plots every Y column against its nearest-preceding X with
its bound Y-error bars (``origin_graph``).

The header comment names Quantized (a deliberate, documented deviation from
the MATLAB golden's ``generated by quantized_matlab`` line).

Pure layer: ``format_origin_script`` returns ``(csv_text, ogs_text)`` (no disk
I/O). The ``created`` timestamp is injected by the caller so the function stays
deterministic (the route passes the wall-clock time; tests pass a fixed value).
"""

from __future__ import annotations

import math
from typing import Any

import numpy as np

from quantized.csv_safe import csv_text_cell
from quantized.datastruct import DataStruct, is_categorical, level_of
from quantized.io._column_roles import (
    LABTALK_COLUMN_TYPE,
    channel_comments,
    channel_designations,
    error_targets,
    x_column_comment,
)
from quantized.io._origin_names import origin_short_name
from quantized.io.origin_graph import (
    GraphSpec,
    curve_set,
    default_graph,
    escape_lt,
    origin_rich_unit,
    plot_state_graph,
)
from quantized.io.origin_x_echo import kept_channels, remap_graph

__all__ = [
    "GraphSpec",
    "format_origin_project_script",
    "format_origin_script",
    "origin_rich_unit",
]

# The comment each LabTalk designation line carries.
_TYPE_COMMENT = {
    "Y": "Y",
    "disregard": "Disregard",
    "Y-error": "yErr",
    "X": "X",
    "label": "Label",
    "Z": "Z",
    "X-error": "xErr",
}


def _meta_get(meta: dict[str, Any], *keys: str, default: Any = None) -> Any:
    """First present, non-empty metadata value among ``keys`` (snake/camel)."""
    for key in keys:
        val = meta.get(key)
        if val not in (None, ""):
            return val
    return default


def _num_cell(v: float) -> str:
    """One ``%.10g`` data cell; a missing (non-finite) value is a BLANK cell,
    which Origin's impASC, Excel and quantized's importer all read as missing
    (``"nan"`` is text to the first two -- Excel charts even plot it as 0)."""
    return f"{v:.10g}" if math.isfinite(v) else ""


def _sanitize(name: str) -> str:
    """A book/sheet name Origin accepts as a short name: the .opj writer's
    rule (io/_origin_names.origin_short_name -- ASCII letters/digits, a
    leading letter, accents folded). The MATLAB port's ``\\W -> _`` kept
    underscores, non-ASCII letters and leading digits, which Origin rejects."""
    return origin_short_name(name, "data")


def format_origin_script(
    data: DataStruct,
    *,
    csv_name: str = "data.csv",
    book_name: str = "",
    sheet_name: str = "",
    log_x: bool = False,
    log_y: bool = False,
    make_graph: bool = True,
    created: str = "",
    book_long_name: str = "",
    graph: GraphSpec | None = None,
) -> tuple[str, str]:
    """Return ``(csv_text, ogs_text)`` for ``data``. Port of exportOriginScript.

    ``csv_name`` is the CSV filename the script references (``impASC``).
    ``book_name``/``sheet_name`` default to the source filename in metadata,
    then ``"data"``; both are sanitized to LabTalk identifiers.

    ``graph`` (item 26), when given, replaces the default all-Y-columns graph
    with a full plot-state export: selected channels, x source, log axes,
    limits, and a secondary Y axis. Ignored when ``make_graph`` is False.
    """
    meta = dict(data.metadata)
    source = _meta_get(meta, "source", "filepath", "filename", default="")
    base = str(source).replace("\\", "/").rsplit("/", 1)[-1].rsplit(".", 1)[0]
    book = _sanitize(book_name or base or "data")
    sheet = _sanitize(sheet_name or book)

    # The X column's display name: its long name when the dataset carries one
    # (an Origin import's `x_column_name` is the SHORT name, e.g. "A"), the
    # same `x_column_long || x_column_name` rule calc/plotting.py uses.
    x_name = str(_meta_get(meta, "x_column_long", "x_column_name", "xColumnName", default="X"))
    x_unit = str(_meta_get(meta, "x_column_unit", "xColumnUnit", default=""))

    # An Origin matrix book's X channel repeats column 1: written once
    # (origin_x_echo). For every other dataset ``keep`` is every channel.
    n_all = len(data.labels)
    keep = kept_channels(data)
    labels = [data.labels[i] for i in keep]
    units = [data.units[i] if i < len(data.units) else "" for i in keep]
    time = np.asarray(data.time, dtype=float)
    values = np.asarray(data.values, dtype=float)[:, keep]

    # ── CSV: header, units, then %.10g data rows ──
    # Names/units come from the imported file: neutralize spreadsheet formulas
    # (OWASP) and quote a cell holding a comma. Numeric rows are untouched.
    csv_lines = [
        ",".join(csv_text_cell(c) for c in [x_name, *labels]),
        ",".join(csv_text_cell(c) for c in [x_unit, *units]),
    ]
    # A categorical channel stores level CODES: write the level text instead.
    categorical = [is_categorical(data, c) for c in keep]
    for r in range(values.shape[0]):
        cells = [_num_cell(time[r])]
        cells.extend(
            csv_text_cell(level_of(data, keep[c], values[r, c]) or "") if categorical[c]
            else _num_cell(values[r, c])
            for c in range(values.shape[1])
        )
        csv_lines.append(",".join(cells))
    csv_text = "\n".join(csv_lines) + "\n"

    # ── LabTalk (.ogs) script ──
    o: list[str] = [
        "// LabTalk script generated by Quantized",
        f"// Date: {created}",
        "",
        "// Import data",
        f'newbook name:="{book}" sheet:=1;',
        # impASC auto-detects the 2-row (name/unit) header AND renames the book +
        # sheet to the source file -- so restore the intended names AFTER import.
        # (The historical `options.SkipRows.Count:=2` sub-option is INVALID LabTalk
        # in current Origin and aborts the whole import; bare impASC reads our
        # 2-header CSV correctly and the explicit designations below re-assert
        # names/units. See docs/origin_project_format.md.)
        f'impASC fname:="{csv_name}";',
        *([f'page.longname$ = "{escape_lt(book_long_name)}";'] if book_long_name else []),
        f'wks.name$ = "{sheet}";',
        # A successful impASC renamed the book; capture its (post-import) short
        # name so the item-26 secondary-axis plotxy can reference the worksheet
        # columns while the GRAPH window -- not the book -- is active.
        *(["string qzbk$ = page.name$;"] if (make_graph and graph is not None) else []),
        "",
        "// Column designations and labels",
        "wks.col1.type = 4;  // X",
        f'wks.col1.lname$ = "{escape_lt(x_name)}";',
        f'wks.col1.unit$ = "{escape_lt(x_unit)}";',
    ]
    x_comment = x_column_comment(meta)
    if x_comment:
        o.append(f'wks.col1.comment$ = "{escape_lt(x_comment)}";')
    # Declared roles decide (column_designations + the live error roles); the
    # whole-token label guess runs only when the dataset declares neither.
    all_designations = channel_designations(meta, list(data.labels), keyword_fallback=True)
    designations = [all_designations[i] for i in keep]
    comments = [channel_comments(meta, n_all)[i] for i in keep]
    for k, label in enumerate(labels):
        cn = k + 2
        unit = units[k] if k < len(units) else ""
        desig = designations[k]
        o.append(f"wks.col{cn}.type = {LABTALK_COLUMN_TYPE[desig]};  // {_TYPE_COMMENT[desig]}")
        o.append(f'wks.col{cn}.lname$ = "{escape_lt(label)}";')
        o.append(f'wks.col{cn}.unit$ = "{escape_lt(unit)}";')
        if comments[k]:
            o.append(f'wks.col{cn}.comment$ = "{escape_lt(comments[k])}";')

    if make_graph:
        new_index = {old: k for k, old in enumerate(keep)}
        targets = {
            new_index[e]: new_index[t]
            for e, t in error_targets(meta, n_all).items()
            if e in new_index and t in new_index
        }
        curves = curve_set(designations, targets)
        if graph is not None:
            graph = remap_graph(graph, keep, n_all)
            o += plot_state_graph(
                graph, labels=labels, units=units, x_name=x_name, x_unit=x_unit, sheet=sheet,
                x_data=time if graph.x_key is None or graph.x_key >= values.shape[1]
                else values[:, graph.x_key],
                curves=curves,
            )
        else:
            o += default_graph(
                curves, labels=labels, units=units, x_name=x_name, x_unit=x_unit,
                log_x=log_x, log_y=log_y,
            )

    o += ["", "// Done"]
    ogs_text = "\n".join(o) + "\n"
    return csv_text, ogs_text


def format_origin_project_script(
    items: list[tuple[DataStruct, str]],
    *,
    created: str = "",
    make_graph: bool = False,
) -> tuple[list[tuple[str, str]], str]:
    """Multi-book export: one LabTalk ``.ogs`` importing N CSVs into N books.

    ``items`` is ``[(dataset, book_name), …]`` (an empty name falls back to the
    dataset's ``origin_book`` metadata, then ``dataN``). Returns
    ``([(csv_name, csv_text), …], ogs_text)`` — the script recreates every
    workbook with designations, long names, units, and the book display title
    (``page.longname$``) when the dataset carries one.
    """
    if not items:
        raise ValueError("format_origin_project_script needs at least one dataset")
    csvs: list[tuple[str, str]] = []
    sections: list[str] = [
        "// LabTalk project script generated by Quantized",
        f"// Date: {created}",
        f"// Books: {len(items)}",
    ]
    used: set[str] = set()
    for i, (ds, name) in enumerate(items):
        meta = dict(ds.metadata)
        # Unique ignoring case, as Origin compares short names.
        raw = str(name or meta.get("origin_book", "") or f"data{i + 1}")
        book = origin_short_name(raw, f"data{i + 1}", used)
        long_name = str(meta.get("origin_book_long", "") or "")
        csv_name = f"{book}_data.csv"
        csv_text, ogs_text = format_origin_script(
            ds,
            csv_name=csv_name,
            book_name=book,
            sheet_name=book,
            make_graph=make_graph,
            created=created,
            book_long_name=long_name if long_name != book else "",
        )
        csvs.append((csv_name, csv_text))
        body = ogs_text.splitlines()
        # drop the per-script header comment lines (kept once at the top)
        while body and body[0].startswith("//"):
            body.pop(0)
        sections += ["", f"// ---- Book {i + 1}: {book} ----", *body]
    return csvs, "\n".join(sections) + "\n"
