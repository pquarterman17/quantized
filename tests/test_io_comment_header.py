"""Column names recovered from a ``#`` comment header (UX audit 8, finding 2).

numpy ``savetxt``, gnuplot and many instrument exports write the header as a
comment (``# Qz (1/A)  R``). Every comment line is preamble, so such files
imported as Col1/Col2 with no units. The last comment line(s) directly above
the data now name the columns when they fit the table exactly; a free-text
comment does not, and the old Col1/Col2 names stand. The comment itself is
still kept in ``metadata["comments"]``.

MATLAB parity: ``+parser/importCSV.m`` never names columns from a comment
line -- a deliberate, additive divergence (PORT_CHECKLIST, generic CSV).
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from quantized.io._comment_header import comment_header, comment_lines_above_data
from quantized.io.delimited import import_csv
from quantized.io.import_preview import guess_settings, parse_import
from quantized.io.registry import import_auto

FX = Path(__file__).parent / "fixtures" / "delimited_text"


def _write(tmp_path: Path, text: str, name: str = "data.txt") -> Path:
    path = tmp_path / name
    path.write_text(text, encoding="utf-8")
    return path


# --- committed synthetic fixtures (also swept by the parser matrix) ----------


@pytest.mark.parametrize(
    ("name", "x", "x_unit", "labels", "units"),
    [
        ("comment_header_xrr.dat", "Qz", "1/A", ["R"], [""]),
        ("comment_header_raman.txt", "Raman shift", "cm-1", ["Intensity"], ["counts"]),
        ("comment_header_units.dat", "Temperature", "K", ["Moment"], ["emu"]),
    ],
)
def test_fixture_columns_are_named_from_the_comment(
    name: str, x: str, x_unit: str, labels: list[str], units: list[str]
) -> None:
    path = FX / name
    ds = import_auto(path)
    assert ds.metadata["parser_name"] == "import_csv"
    assert ds.metadata["x_column_name"] == x
    assert ds.metadata["x_column_unit"] == x_unit
    assert list(ds.labels) == labels
    assert list(ds.units) == units
    assert ds.values.shape[0] == 24 and np.isfinite(ds.values).all()
    # Additive: the comment is still kept, and the promotion is announced.
    assert any(c.startswith("#") for c in ds.metadata["comments"])
    assert any("comment line" in n for n in ds.metadata["notes"])
    # The Import Wizard's guess names the columns the same way.
    text = path.read_text(encoding="utf-8")
    wiz = parse_import(text, guess_settings(text))
    assert wiz.metadata["x_column_name"] == x
    assert list(wiz.labels) == labels and list(wiz.units) == units
    assert guess_settings(text).header_line is None  # never a comment row


# --- the shapes the promotion accepts ------------------------------------------


@pytest.mark.parametrize(
    ("text", "x", "labels"),
    [
        ("# Field (Oe)\tMoment (emu)\n1\t2\n3\t4\n", "Field", ["Moment"]),
        ("# x,y,z\n1,2,3\n3,5,6\n", "x", ["y", "z"]),  # savetxt(delimiter=",")
        ("# x y\n1 2\n3 4\n", "x", ["y"]),  # gnuplot
        ("% time  signal\n1 2\n3 4\n", "time", ["signal"]),  # MATLAB-style comment
        ("## T [K]  M [emu]\n\n1 2\n3 4\n", "T", ["M"]),  # blank line, "##"
        ("# H (Oe) M (emu)\n1 2\n3 4\n", "H", ["M"]),  # units glue to their names
        ("# Run 7, CoFeB\n\n# T\tR\n1\t2\n3\t4\n", "T", ["R"]),  # last block only
    ],
)
def test_comment_header_names_columns(
    tmp_path: Path, text: str, x: str, labels: list[str]
) -> None:
    ds = import_csv(_write(tmp_path, text))
    assert ds.metadata["x_column_name"] == x
    assert list(ds.labels) == labels
    assert ds.time.tolist()[:2] == [1.0, 3.0]


# --- free-text comments are left alone ---------------------------------------------


@pytest.mark.parametrize(
    "text",
    [
        "# Sample: CoFeB film\n1 2\n3 4\n",  # key: value
        "# operator = JS\n1 2\n3 4\n",  # key = value
        "# generated by numpy\n1 2 3\n4 5 6\n",  # prose split at single spaces
        "# Measured at 300 K\n1 2\n3 4\n",  # holds a number / wrong count
        "# Field cooled.\n1 2\n3 4\n",  # a sentence
        "# a b c\n1 2\n3 4\n",  # three names over two columns
        "# (Oe)  (emu)\n1 2\n3 4\n",  # units with no names
    ],
)
def test_free_text_comment_is_not_a_header(tmp_path: Path, text: str) -> None:
    ds = import_csv(_write(tmp_path, text))
    names = [ds.metadata["x_column_name"], *ds.labels]
    assert all(n.startswith("Col") for n in names), names
    assert ds.metadata["comments"]
    assert not any("comment line" in n for n in ds.metadata.get("notes", []))


def test_a_real_header_row_wins_over_a_comment(tmp_path: Path) -> None:
    text = "# Field  Moment\nH (Oe)\tM (emu)\n1\t2\n3\t4\n"
    ds = import_csv(_write(tmp_path, text))
    assert ds.metadata["x_column_name"] == "H"
    assert list(ds.labels) == ["M"]


def test_comment_separated_by_a_non_comment_line_is_not_used() -> None:
    lines = ["# x y", "[Header]", "1 2"]
    assert comment_lines_above_data(lines) == []
    assert comment_header(["# x y", "1 2"], " ", 2) is not None
    assert comment_header(["# x y", "1 2"], " ", 1) is None


def test_units_line_needs_brackets_on_every_cell() -> None:
    got = comment_header(["# Temperature  Moment", "# (K)  (emu)", "1 2"], " ", 2)
    assert got is not None and got.names == ["Temperature", "Moment"]
    assert got.units == ["K", "emu"]
    assert got.names_with_units() == ["Temperature (K)", "Moment (emu)"]
    plain = comment_header(["# Created  by", "# x  y", "1 2"], " ", 2)
    assert plain is not None and plain.names == ["x", "y"] and plain.units == []
