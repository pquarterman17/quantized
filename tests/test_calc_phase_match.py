"""Phase search/match (calc/phase_match.py): synthetic oracles.

Reference peaks are generated by the app's own pattern code (``phase_reflections``,
golden-verified ``plane_spacings``) from the database cells; nothing is typed from
memory. The tests add a shift, noise and spurious peaks and assert recovery.
"""

from __future__ import annotations

import math
import random

import pytest

from quantized.calc.phase_match import match_phases
from quantized.calc.xrd_index import phase_reflections

WL = 1.5406
RANGE = {"two_theta_min": 20.0, "two_theta_max": 90.0}


def _lines(name: str, n: int | None = None) -> list[float]:
    rows = phase_reflections(name, wavelength=WL, two_theta_min=20, two_theta_max=90)["reflections"]
    return [float(r["two_theta"]) for r in rows][:n]


def _noisy(tts: list[float], seed: int, shift: float = 0.03, sigma: float = 0.02) -> list[float]:
    rng = random.Random(seed)
    return [t + shift + rng.gauss(0, sigma) for t in tts]


def test_single_phase_ranks_first_with_shift_noise_and_spurious() -> None:
    for name in ("Silicon", "MgO", "Tungsten", "ZnO (wurtzite)"):
        base = _lines(name)
        peaks = sorted(_noisy(base, 1) + [33.3, 61.7])
        r = match_phases(peaks, wavelength=WL, **RANGE)
        assert r["phases"][0]["name"] == name
        assert r["ranked"][0]["name"] == name
        assert 33.3 in [u["two_theta"] for u in r["unexplained"]]


def test_two_phase_mixture_recovers_both() -> None:
    si, au = _lines("Silicon"), _lines("Tungsten")
    peaks = sorted(_noisy(si, 2) + _noisy(au, 3))
    r = match_phases(peaks, wavelength=WL, **RANGE)
    names = [p["name"] for p in r["phases"]]
    assert set(names[:2]) == {"Silicon", "Tungsten"}
    assert r["phases"][1]["step"] == 2
    # residual step: second phase scored only on the peaks the first left over
    first_hits = {m["peak_index"] for m in r["phases"][0]["matches"]}
    assert not first_hits & {m["peak_index"] for m in r["phases"][1]["matches"]}


def test_d_input_equals_two_theta_input() -> None:
    base = _lines("Silicon")
    d = [WL / (2 * math.sin(math.radians(t / 2))) for t in base]
    a = match_phases(base, wavelength=WL, **RANGE)
    b = match_phases(d, peak_unit="d", wavelength=WL, **RANGE)
    assert a["phases"][0]["name"] == b["phases"][0]["name"] == "Silicon"
    assert a["phases"][0]["fom"] == pytest.approx(b["phases"][0]["fom"], abs=1e-9)


def test_perfect_match_fom_is_one() -> None:
    pat = {
        "name": "P",
        "lines": [{"two_theta": t, "intensity": i} for t, i in [(30, 100), (40, 50), (50, 20)]],
    }
    r = match_phases(
        [30, 40, 50],
        intensities=[100, 50, 20],
        wavelength=WL,
        patterns=[pat],
        include_builtin=False,
        **RANGE,
    )
    assert r["phases"][0]["fom"] == pytest.approx(1.0)
    assert r["phases"][0]["intensity_term"] == pytest.approx(1.0)


def test_intensity_term_breaks_a_position_tie() -> None:
    lines = [30.0, 40.0, 50.0]
    good = {
        "name": "good",
        "lines": [
            {"two_theta": t, "intensity": i} for t, i in zip(lines, (100, 50, 20), strict=True)
        ],
    }
    bad = {
        "name": "bad",
        "lines": [
            {"two_theta": t, "intensity": i} for t, i in zip(lines, (20, 50, 100), strict=True)
        ],
    }
    r = match_phases(
        lines,
        intensities=[100, 50, 20],
        wavelength=WL,
        patterns=[bad, good],
        include_builtin=False,
        **RANGE,
    )
    assert [c["name"] for c in r["ranked"]] == ["good", "bad"]


def test_missing_weak_reference_lines_do_not_count_against_phase() -> None:
    pat = {
        "name": "P",
        "lines": [{"two_theta": 30, "intensity": 100}, {"two_theta": 60, "intensity": 2}],
    }
    r = match_phases([30.0], wavelength=WL, patterns=[pat], include_builtin=False, **RANGE)
    assert r["phases"][0]["f_ref"] == 1.0  # the 2 % line is not "strong"
    r2 = match_phases(
        [30.0], wavelength=WL, patterns=[pat], include_builtin=False, strong_fraction=0.0, **RANGE
    )
    assert r2["phases"][0]["f_ref"] == 0.5


def test_pattern_wavelength_conversion() -> None:
    # Cu Ka1 reference stick re-expressed at another wavelength via d.
    cu = phase_reflections("Silicon", wavelength=1.5406, two_theta_min=20, two_theta_max=80)[
        "reflections"
    ]
    co = phase_reflections("Silicon", wavelength=1.78897, two_theta_min=20, two_theta_max=100)[
        "reflections"
    ]
    pat = {
        "name": "Si-cu",
        "wavelength": 1.5406,
        "lines": [{"two_theta": r["two_theta"]} for r in cu],
    }
    r = match_phases(
        [float(x["two_theta"]) for x in co[:4]],
        wavelength=1.78897,
        two_theta_min=20,
        two_theta_max=100,
        patterns=[pat],
        include_builtin=False,
        tolerance=0.01,
    )
    assert r["phases"][0]["n_matched"] == 4
    assert r["phases"][0]["wavelength_assumed"] is False


@pytest.mark.parametrize(
    "kwargs,msg",
    [
        ({"wavelength": 0.0}, "wavelength"),
        ({"wavelength": float("nan")}, "wavelength"),
        ({"peaks": []}, "at least one peak"),
        ({"peaks": [30, -1]}, "positive"),
        ({"intensities": [1.0]}, "one value per peak"),
        ({"intensities": [1.0, -1.0, 2.0]}, "non-negative"),
        ({"tolerance": 9.0}, "tolerance"),
        ({"peak_unit": "q"}, "peak_unit"),
        ({"include_builtin": False}, "no phases to search"),
        ({"peaks": [95.0, 96.0]}, "inside the 2theta range"),
    ],
)
def test_refusals(kwargs: dict, msg: str) -> None:
    base: dict = {"peaks": [30.0, 40.0, 50.0], "wavelength": WL, **RANGE}
    base.update(kwargs)
    peaks = base.pop("peaks")
    with pytest.raises(ValueError, match=msg):
        match_phases(peaks, **base)


def test_pattern_needs_exactly_one_position_key() -> None:
    with pytest.raises(ValueError, match="exactly one"):
        match_phases(
            [30.0],
            wavelength=WL,
            include_builtin=False,
            **RANGE,
            patterns=[{"name": "x", "lines": [{"two_theta": 30, "d": 3}]}],
        )


def test_chance_guard_and_no_match_gives_no_phase() -> None:
    r = match_phases(
        [21.0],
        wavelength=WL,
        patterns=[{"name": "far", "lines": [{"two_theta": 70}]}],
        include_builtin=False,
        **RANGE,
    )
    assert r["phases"] == [] and r["unexplained"][0]["two_theta"] == 21.0


@pytest.mark.parametrize("name", ["Gold", "Silver", "Copper", "Platinum"])
def test_similar_fcc_metals_are_told_apart_at_tight_tolerance(name: str) -> None:
    peaks = [t + 0.03 for t in _lines(name)]
    r = match_phases(peaks, wavelength=WL, tolerance=0.1, **RANGE)
    assert r["ranked"][0]["name"] == name


def test_route_roundtrip_and_refusals() -> None:
    from fastapi.testclient import TestClient

    from quantized.app import create_app  # noqa: PLC0415

    c = TestClient(create_app())
    body = {"peaks": _lines("Silicon"), "wavelength": WL, **RANGE}
    ok = c.post("/api/reductions/xrd-match", json=body)
    assert ok.status_code == 200 and ok.json()["phases"][0]["name"] == "Silicon"
    nowl = {k: v for k, v in body.items() if k != "wavelength"}
    assert c.post("/api/reductions/xrd-match", json=nowl).status_code == 422
    nodb = c.post("/api/reductions/xrd-match", json={**body, "include_builtin": False})
    assert nodb.status_code in (400, 422) and "no phases" in nodb.text


def test_chance_guard_off_labels_peaks_near_a_dense_pattern() -> None:
    dense = {"name": "dense", "lines": [{"two_theta": 20 + 0.1 * k} for k in range(700)]}
    on = match_phases([45.03], wavelength=WL, patterns=[dense], include_builtin=False, **RANGE)
    off = match_phases([45.03], wavelength=WL, patterns=[dense], include_builtin=False,
                       chance_guard=False, min_fom=0.0, **RANGE)
    assert on["phases"] == [] and off["phases"][0]["matches"][0]["label"] == ""
